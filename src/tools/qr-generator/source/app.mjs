/* ============================================================================
 * Persistence: UI state (input + options) survives a reload via localStorage.
 * Namespaced, versioned key; best-effort — every read/write is wrapped in
 * try/catch and degrades silently, so the tool works fully with no stored
 * state (localStorage can be unavailable under file://, private mode, quota,
 * or browser policy). The rendered QR/canvas/matrix is DERIVED and is never
 * persisted — it's recomputed from the restored input+options on load.
 * ==========================================================================*/

const STORAGE_KEY = 'qr-generator:v1';
const HELP_SEEN_KEY = 'qr-generator:help-seen:v1';

function saveState() {
  try {
    localStorage.setItem(
      STORAGE_KEY,
      JSON.stringify({
        input: inputEl.value,
        ecLevel: ecLevelEl.value,
        scale: scaleEl.value,
        quietZone: quietZoneEl.value,
        fg: fgEl.value,
        bg: bgEl.value,
      }),
    );
  } catch (err) {
    // Best-effort: localStorage unavailable (file://, private mode, quota,
    // browser policy). Degrade silently to in-memory only.
  }
}

function loadState() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return null;
    const parsed = JSON.parse(raw);
    return parsed && typeof parsed === 'object' ? parsed : null;
  } catch (err) {
    return null;
  }
}

// Applies stored state onto the live form fields, validating each field
// independently and falling back to the field's current markup default
// whenever a stored value is missing or malformed. Never touches the
// canvas/matrix (derived — re-rendered separately by the caller).
function applyStoredState() {
  const stored = loadState();
  if (!stored) return;
  if (typeof stored.input === 'string') inputEl.value = stored.input;
  if (typeof stored.ecLevel === 'string' && ['L', 'M', 'Q', 'H'].includes(stored.ecLevel)) {
    ecLevelEl.value = stored.ecLevel;
  }
  if (typeof stored.scale === 'string' || typeof stored.scale === 'number') {
    scaleEl.value = String(stored.scale);
  }
  if (typeof stored.quietZone === 'string' || typeof stored.quietZone === 'number') {
    quietZoneEl.value = String(stored.quietZone);
  }
  if (typeof stored.fg === 'string' && /^#[0-9a-fA-F]{6}$/.test(stored.fg)) fgEl.value = stored.fg;
  if (typeof stored.bg === 'string' && /^#[0-9a-fA-F]{6}$/.test(stored.bg)) bgEl.value = stored.bg;
}

// Whether the visitor has already dismissed the Help modal at least once.
// If localStorage throws/is unavailable, treat it as already-seen so we
// don't nag on every load — the least-annoying safe fallback (the ?
// button is always there if they want the modal later).
function hasSeenHelp() {
  try {
    return localStorage.getItem(HELP_SEEN_KEY) === '1';
  } catch (err) {
    return true;
  }
}

function markHelpSeen() {
  try {
    localStorage.setItem(HELP_SEEN_KEY, '1');
  } catch (err) {
    // Best-effort, same as saveState().
  }
}

function truncate(str, n) {
  return str.length > n ? str.slice(0, n - 1) + '…' : str;
}

function currentOptions() {
  return {
    scale: Math.max(1, Math.min(40, parseInt(scaleEl.value, 10) || 8)),
    quietZone: Math.max(0, Math.min(20, parseInt(quietZoneEl.value, 10) || 0)),
    fg: fgEl.value || '#000000',
    bg: bgEl.value || '#ffffff',
  };
}

function showError(message) {
  errorEl.textContent = message;
  errorEl.classList.add('visible');
}
function clearError() {
  errorEl.textContent = '';
  errorEl.classList.remove('visible');
}

function clearCanvas() {
  canvasEl.classList.add('hidden');
  const ctx = canvasEl.getContext('2d');
  ctx.clearRect(0, 0, canvasEl.width, canvasEl.height);
}

function disableDownloads() {
  downloadPngBtn.disabled = true;
  downloadSvgBtn.disabled = true;
}
function enableDownloads() {
  downloadPngBtn.disabled = false;
  downloadSvgBtn.disabled = false;
}

function updateContrastWarning() {
  const { fg, bg } = currentOptions();
  let ratio;
  try {
    ratio = contrastRatio(fg, bg);
  } catch {
    ratio = 21; // malformed color input — don't warn
  }
  if (ratio < 3) {
    contrastWarningEl.textContent = 'Low contrast between foreground and background — this code may not scan reliably.';
    contrastWarningEl.classList.add('visible');
  } else {
    contrastWarningEl.textContent = '';
    contrastWarningEl.classList.remove('visible');
  }
}

function doRender() {
  const text = inputEl.value;
  const ecLevel = ecLevelEl.value;
  clearError();
  updateContrastWarning();

  if (text.trim() === '') {
    clearCanvas();
    disableDownloads();
    captionEl.textContent = '';
    capacityHintEl.textContent = 'Enter text or a URL above to generate a QR code.';
    currentMatrix = null;
    return;
  }

  try {
    currentMatrix = encodeToMatrix(text, ecLevel);
  } catch (err) {
    clearCanvas();
    disableDownloads();
    showError(err.message);
    capacityHintEl.textContent = '';
    captionEl.textContent = '';
    currentMatrix = null;
    return;
  }

  canvasEl.classList.remove('hidden');
  renderToCanvas(canvasEl, currentMatrix, currentOptions());
  captionEl.textContent = `Version ${currentMatrix.version} · Level ${ecLevel}`;
  capacityHintEl.textContent = `Version ${currentMatrix.version} of 40 · Level ${ecLevel}`;
  canvasEl.setAttribute('aria-label', `QR code for: ${truncate(text, 60)}`);
  enableDownloads();
}

// In-field copy on the editable text/URL input: revealed only when the field
// is non-empty (CSS can't read a value, so the tool toggles [hidden]). The QR
// output is an image, so this input is the one copyable text value in the tool.
function syncCopyBtn() {
  if (copyInputBtn) copyInputBtn.hidden = inputEl.value.trim() === '';
}

if (copyInputBtn) {
  copyInputBtn.addEventListener('click', async () => {
    const text = inputEl.value;
    if (!text) return;
    const ok = await copy(text);
    if (!ok) return;
    flash(copyInputBtn, { label: '✅', revertTo: '📋' });
  });
}

// Shared trailing-edge debounce (jbc-include/util.js, inlined as a global).
const scheduleRender = debounce(doRender, 150);

[inputEl, ecLevelEl, scaleEl, quietZoneEl, fgEl, bgEl].forEach((el) => {
  el.addEventListener('input', () => {
    saveState();
    scheduleRender();
  });
});

// Keep the in-field copy button's visibility in sync with the input's value.
inputEl.addEventListener('input', syncCopyBtn);

downloadPngBtn.addEventListener('click', () => {
  if (!currentMatrix) return;
  const rawUrl = canvasEl.toDataURL('image/png');
  // Best-effort: embed Author/Source/Software tEXt metadata; addPngMetadata
  // never throws, so a bad injection just falls back to the plain PNG.
  const url = addPngMetadata(rawUrl);
  // addPngMetadata returns a PNG data URL (metadata-injected, or the original
  // on best-effort failure); decode it to bytes so the shared download helper
  // (jbc-include/util.js) can save the exact PNG content.
  const bytes = dataUrlToBytes(url);
  downloadBlob(new Blob([bytes], { type: 'image/png' }), `qr-code-v${currentMatrix.version}-${ecLevelEl.value}.png`);
});

downloadSvgBtn.addEventListener('click', () => {
  if (!currentMatrix) return;
  const svg = toSVGString(currentMatrix, currentOptions());
  const blob = new Blob([svg], { type: 'image/svg+xml' });
  // Shared download helper (jbc-include/util.js, inlined as a global).
  downloadBlob(blob, `qr-code-v${currentMatrix.version}-${ecLevelEl.value}.svg`);
});

/* ============================================================================
 * Help modal -- purely informational (what the tool does + how to use it),
 * so it's its own small dedicated dialog rather than confirmDialog (which is a
 * yes/no destructive-action confirm). Markup is static in the document
 * (shown/hidden via [hidden]) rather than built/torn down per open/close.
 * Structure/focus-handling mirrors tools/hat-picker and tools/color-designer
 * (see docs/conventions.md "First-load help popup (all tools)").
 * ==========================================================================*/

let helpPreviouslyFocused = null;

function getHelpFocusable() {
  return Array.from(
    helpDialogEl.querySelectorAll('button, [href], input, select, textarea, [tabindex]:not([tabindex="-1"])'),
  ).filter((el) => !el.disabled && el.getClientRects().length > 0);
}

function onHelpKeydown(e) {
  if (e.key === 'Escape') {
    e.preventDefault();
    closeHelp();
    return;
  }
  if (e.key !== 'Tab') return;
  const focusable = getHelpFocusable();
  if (focusable.length === 0) return;
  e.preventDefault();
  const idx = focusable.indexOf(document.activeElement);
  let next = e.shiftKey ? idx - 1 : idx + 1;
  if (next < 0) next = focusable.length - 1;
  if (next >= focusable.length) next = 0;
  focusable[next].focus();
}

function openHelp() {
  helpPreviouslyFocused = document.activeElement;
  helpOverlayEl.hidden = false;
  document.addEventListener('keydown', onHelpKeydown, true);
  helpDialogEl.scrollTop = 0;
  helpCloseXEl.focus({ preventScroll: true });
}

function closeHelp() {
  if (helpOverlayEl.hidden) return;
  helpOverlayEl.hidden = true;
  document.removeEventListener('keydown', onHelpKeydown, true);
  if (helpPreviouslyFocused && typeof helpPreviouslyFocused.focus === 'function') {
    try { helpPreviouslyFocused.focus(); } catch (err) { /* ignore */ }
  }
  helpPreviouslyFocused = null;
}

helpButtonEl.addEventListener('click', () => openHelp());
helpCloseXEl.addEventListener('click', () => closeHelp());
helpOverlayEl.addEventListener('mousedown', (e) => {
  if (e.target === helpOverlayEl) closeHelp();
});

// Restore persisted UI state (input + options) before the initial paint;
// best-effort — falls back to the markup defaults when there's nothing
// stored or it can't be read (see Persistence above). The canvas/matrix
// itself is never stored — this only re-renders it from restored inputs.
applyStoredState();

// Reflect the restored input value in the in-field copy button's visibility
// (applyStoredState sets .value directly, which fires no `input` event).
syncCopyBtn();

// Initial paint.
doRender();

// Auto-show the Help modal once, on a genuinely fresh visit only. Marking
// it seen right away (rather than on close) keeps this a true "once" --
// even if the visitor navigates away without explicitly closing it, it
// won't auto-show again next time.
if (!hasSeenHelp()) {
  markHelpSeen();
  openHelp();
}

