function renderToCanvas(canvas, matrixResult, options) {
  const { size, modules } = matrixResult;
  const { scale = 8, quietZone = 4, fg = '#000000', bg = '#ffffff' } = options || {};
  const total = size + quietZone * 2;
  canvas.width = total * scale;
  canvas.height = total * scale;
  const ctx = canvas.getContext('2d');
  ctx.imageSmoothingEnabled = false;
  ctx.fillStyle = bg;
  ctx.fillRect(0, 0, canvas.width, canvas.height);
  ctx.fillStyle = fg;
  for (let r = 0; r < size; r++) {
    for (let c = 0; c < size; c++) {
      if (modules[r][c]) ctx.fillRect((c + quietZone) * scale, (r + quietZone) * scale, scale, scale);
    }
  }
}

// Repo/attribution constants shared by the PNG tEXt chunks (below) and the
// SVG metadata block, so both export paths agree on the exact same strings.
const TOOL_AUTHOR = 'claude tools';
const TOOL_REPO_URL = 'https://github.com/codercowboy/claude-tools';
const TOOL_SOFTWARE = 'claude-tools qr-generator';

// Embeds attribution metadata in the exported SVG: a leading XML comment
// (visible to anyone who opens the file as text) plus a Dublin-Core
// <metadata> block (machine-readable, standard SVG/XML practice) — same
// author + repo URL as the PNG's tEXt chunks. Purely additive markup; the
// visible <rect>/<path> geometry is unchanged, so the code stays crisp and
// scannable.
function toSVGString(matrixResult, options) {
  const { size, modules } = matrixResult;
  const { quietZone = 4, fg = '#000000', bg = '#ffffff' } = options || {};
  const total = size + quietZone * 2;
  let path = '';
  for (let r = 0; r < size; r++) {
    for (let c = 0; c < size; c++) {
      if (modules[r][c]) path += `M${c + quietZone},${r + quietZone}h1v1h-1z`;
    }
  }
  const comment = `<!-- Generated by ${TOOL_SOFTWARE} — ${TOOL_REPO_URL} -->`;
  const metadata =
    `<metadata><dc:creator>${TOOL_AUTHOR}</dc:creator><dc:source>${TOOL_REPO_URL}</dc:source></metadata>`;
  return (
    comment +
    `<svg xmlns="http://www.w3.org/2000/svg" xmlns:dc="http://purl.org/dc/elements/1.1/" viewBox="0 0 ${total} ${total}" width="${total * 8}" height="${total * 8}" shape-rendering="crispEdges">` +
    metadata +
    `<rect width="${total}" height="${total}" fill="${bg}"/>` +
    `<path d="${path}" fill="${fg}"/>` +
    `</svg>`
  );
}

/* ----------------------------------------------------------------------
 * Hand-rolled PNG tEXt-chunk injector (no library).
 *
 * canvas.toDataURL('image/png')/toBlob() produce a PNG with no custom
 * metadata — there's no browser API to add ancillary chunks. This parses
 * the PNG chunk stream (8-byte signature, then a sequence of
 * length(4 BE) + type(4 ASCII) + data(length) + CRC-32(4) chunks per the
 * PNG spec / ISO/IEC 15948) and inserts new tEXt chunks just before IEND.
 * Every other chunk — including IHDR and all IDAT (pixel) data — is copied
 * through byte-for-byte and never touched, so the rendered QR code's pixels
 * (and therefore its decodability) are completely unaffected; only chunk
 * framing is added.
 * ------------------------------------------------------------------- */

const PNG_SIGNATURE = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a];

// Standard CRC-32 (ISO 3309 / ITU-T V.42), the exact algorithm the PNG spec
// requires for each chunk's trailing CRC. Shared impl: jbc-include/crc32.js,
// the crc32 export of the CtByteUtil module inlined ahead of this one.

// Builds one complete chunk (length + 4-char type + data + CRC) as bytes.
function buildPngChunk(type, data) {
  const out = new Uint8Array(12 + data.length);
  const view = new DataView(out.buffer);
  view.setUint32(0, data.length, false);
  for (let i = 0; i < 4; i++) out[4 + i] = type.charCodeAt(i);
  out.set(data, 8);
  view.setUint32(8 + data.length, crc32(out.subarray(4, 8 + data.length)), false);
  return out;
}

// tEXt chunk data = keyword (Latin-1, 1-79 chars) + 0x00 separator + text
// (Latin-1, uncompressed). Keywords/text used by this tool are known-good
// ASCII, so no further Latin-1 validation/escaping is needed here.
function buildTextChunk(keyword, text) {
  const data = new Uint8Array(keyword.length + 1 + text.length);
  for (let i = 0; i < keyword.length; i++) data[i] = keyword.charCodeAt(i) & 0xff;
  data[keyword.length] = 0x00;
  for (let i = 0; i < text.length; i++) data[keyword.length + 1 + i] = text.charCodeAt(i) & 0xff;
  return buildPngChunk('tEXt', data);
}

// Walks the chunk stream into { type, bytes } entries (bytes = the chunk's
// full length+type+data+crc span), so chunks can be reassembled verbatim.
function parsePngChunks(bytes) {
  for (let i = 0; i < 8; i++) {
    if (bytes[i] !== PNG_SIGNATURE[i]) throw new Error('not a PNG (bad signature)');
  }
  const chunks = [];
  let offset = 8;
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  while (offset < bytes.length) {
    const length = view.getUint32(offset, false);
    const type = String.fromCharCode(
      bytes[offset + 4], bytes[offset + 5], bytes[offset + 6], bytes[offset + 7],
    );
    const chunkEnd = offset + 12 + length;
    chunks.push({ type, bytes: bytes.subarray(offset, chunkEnd) });
    offset = chunkEnd;
  }
  return chunks;
}

// Returns a new PNG byte stream with tEXt chunks for each { keyword, text }
// entry inserted immediately before IEND. Throws if `pngBytes` doesn't look
// like a PNG or has no IEND — callers should catch and fall back to the
// original, unmodified bytes.
function injectPngTextChunks(pngBytes, entries) {
  const chunks = parsePngChunks(pngBytes);
  const iendIndex = chunks.findIndex((c) => c.type === 'IEND');
  if (iendIndex === -1) throw new Error('no IEND chunk found');
  const textChunks = entries.map(({ keyword, text }) => buildTextChunk(keyword, text));
  const totalLength =
    8 +
    chunks.reduce((sum, c) => sum + c.bytes.length, 0) +
    textChunks.reduce((sum, c) => sum + c.length, 0);
  const out = new Uint8Array(totalLength);
  out.set(PNG_SIGNATURE, 0);
  let pos = 8;
  for (let i = 0; i < iendIndex; i++) {
    out.set(chunks[i].bytes, pos);
    pos += chunks[i].bytes.length;
  }
  for (const tc of textChunks) {
    out.set(tc, pos);
    pos += tc.length;
  }
  out.set(chunks[iendIndex].bytes, pos);
  return out;
}

function dataUrlToBytes(dataUrl) {
  const binary = atob(dataUrl.split(',')[1]);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  return bytes;
}

// The metadata embedded in every downloaded PNG (Author + repo URL, plus a
// Software tag) — same attribution as the SVG export's <metadata> block.
const PNG_METADATA_ENTRIES = [
  { keyword: 'Author', text: TOOL_AUTHOR },
  { keyword: 'Source', text: TOOL_REPO_URL },
  { keyword: 'Software', text: TOOL_SOFTWARE },
];

// Takes a canvas's plain `toDataURL('image/png')` data URL and returns a
// same-content PNG data URL with the tEXt metadata chunks injected. Never
// throws: any failure anywhere in the injection falls back to returning the
// original, unmodified data URL, so a download can never break because of
// this best-effort enhancement.
function addPngMetadata(dataUrl) {
  try {
    const bytes = dataUrlToBytes(dataUrl);
    const withMetadata = injectPngTextChunks(bytes, PNG_METADATA_ENTRIES);
    let binary = '';
    for (let i = 0; i < withMetadata.length; i++) binary += String.fromCharCode(withMetadata[i]);
    return 'data:image/png;base64,' + btoa(binary);
  } catch (err) {
    return dataUrl;
  }
}

/* ============================================================================
 * Contrast check (WCAG relative luminance / contrast ratio)
 * ==========================================================================*/

function hexToRgb(hex) {
  const clean = hex.replace('#', '');
  const full = clean.length === 3 ? clean.split('').map((ch) => ch + ch).join('') : clean;
  const n = parseInt(full, 16);
  return { r: (n >> 16) & 255, g: (n >> 8) & 255, b: n & 255 };
}
function relLuminance(hex) {
  const { r, g, b } = hexToRgb(hex);
  const chan = (v) => {
    const s = v / 255;
    return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
  };
  return 0.2126 * chan(r) + 0.7152 * chan(g) + 0.0722 * chan(b);
}
function contrastRatio(hex1, hex2) {
  const l1 = relLuminance(hex1);
  const l2 = relLuminance(hex2);
  const lighter = Math.max(l1, l2);
  const darker = Math.min(l1, l2);
  return (lighter + 0.05) / (darker + 0.05);
}

